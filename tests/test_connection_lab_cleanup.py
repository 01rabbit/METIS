"""Disposable lab credentials are removed only after confirmed shutdown; no Docker calls."""

import importlib.util
import io
import json
import subprocess
import tempfile
import unittest
from contextlib import redirect_stderr, redirect_stdout
from pathlib import Path
from types import SimpleNamespace
from unittest.mock import patch

_SPEC = importlib.util.spec_from_file_location(
    "connection_lab", Path(__file__).resolve().parent.parent / "scripts" / "connection_lab.py"
)
lab = importlib.util.module_from_spec(_SPEC)
_SPEC.loader.exec_module(lab)


class ConnectionCleanupTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name).resolve()
        self.state = self.root / ".metis-state/connection-lab/0123456789ab"

    def run_lab(self, shutdown_timeout=False):
        shutdown_observed = []

        def fake_run(command, **kwargs):
            if command[:2] == ["docker", "cp"]:
                for name in lab.GENERATED_SECRET_FILES:
                    (self.state / name).write_text("inert disposable credential fixture")
                (self.state / "results.json").write_text('{"fixture": true}')
                (self.state / "rdp-desktop.png").write_bytes(b"inert screenshot fixture")
                (self.state / "ca.crt").write_text("inert public certificate fixture")
            if "down" in command:
                shutdown_observed.append(
                    all((self.state / name).exists() for name in lab.GENERATED_SECRET_FILES)
                )
                if shutdown_timeout:
                    raise subprocess.TimeoutExpired(command, 60)
            return SimpleNamespace(returncode=0)

        with (
            patch.object(lab, "ROOT", self.root),
            patch.object(lab.uuid, "uuid4", return_value=SimpleNamespace(hex="0123456789abcdef")),
            patch.object(lab.subprocess, "run", side_effect=fake_run),
            patch.object(lab.os, "umask"),
            patch.object(lab.sys, "argv", ["connection_lab.py", "--skip-build"]),
            redirect_stdout(io.StringIO()),
            redirect_stderr(io.StringIO()),
        ):
            status = lab.main()
        self.assertEqual(shutdown_observed, [True], "credentials must survive until shutdown is confirmed")
        return status, json.loads((self.state / "cleanup.json").read_text())

    def test_confirmed_shutdown_removes_only_generated_credentials_and_records_it(self):
        status, receipt = self.run_lab()
        self.assertEqual(status, 0)
        self.assertEqual(receipt["generated_secrets"]["status"], "complete")
        self.assertEqual(set(receipt["generated_secrets"]["removed"]), set(lab.GENERATED_SECRET_FILES))
        self.assertTrue(all(not (self.state / name).exists() for name in lab.GENERATED_SECRET_FILES))
        self.assertEqual((self.state / "results.json").read_text(), '{"fixture": true}')
        self.assertTrue((self.state / "rdp-desktop.png").exists())
        self.assertTrue((self.state / "ca.crt").exists())

    def test_unknown_shutdown_retains_credentials_for_reconciliation(self):
        status, receipt = self.run_lab(shutdown_timeout=True)
        self.assertEqual(status, 1)
        self.assertEqual(receipt["returncode"], 124)
        self.assertEqual(receipt["generated_secrets"]["status"], "retained-shutdown-unconfirmed")
        self.assertEqual(receipt["generated_secrets"]["removed"], [])
        self.assertTrue(all((self.state / name).exists() for name in lab.GENERATED_SECRET_FILES))

    def test_scoped_removal_does_not_follow_links_or_recursively_delete_directories(self):
        self.state.mkdir(parents=True)
        outside = self.root / "unrelated-file"
        outside.write_text("preserve unrelated data")
        (self.state / "client_key").symlink_to(outside)
        (self.state / "ca.key").mkdir()
        (self.state / "unrelated.key").write_text("not generated by this lab")
        receipt = lab.cleanup_generated_secrets(self.state, 0)
        self.assertEqual(receipt["status"], "failed")
        self.assertEqual(receipt["errors"][0]["file"], "ca.key")
        self.assertEqual(outside.read_text(), "preserve unrelated data")
        self.assertTrue((self.state / "ca.key").is_dir())
        self.assertTrue((self.state / "unrelated.key").exists())
        alias = self.root / "alias"
        alias.symlink_to(self.state, target_is_directory=True)
        self.assertEqual(lab.cleanup_generated_secrets(alias, 0)["status"], "failed")


if __name__ == "__main__":
    unittest.main()
